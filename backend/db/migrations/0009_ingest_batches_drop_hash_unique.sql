-- Миграция 0009 — повтор пачки сравнивается только с последней несобранной пачкой.
--
-- Уникальный индекс (kind, payload_hash) по несобранным пачкам из 0007 считал дублем любую
-- пачку, совпавшую с ЛЮБОЙ несобранной: последовательность qty 5 → 7 → 5 в одной загрузке
-- теряла последнее значение (третья пачка отбрасывалась как повтор первой, собиралось 7).
-- Теперь дубль — только повтор последней пачки (ретрай); повторы безвредны и без дедупа:
-- при сборке по каждому товару берётся последняя пачка.

DROP INDEX IF EXISTS ux_ingest_batches_pending_hash;
CREATE INDEX IF NOT EXISTS ix_ingest_batches_pending_hash
    ON ingest_batches (kind, payload_hash) WHERE merged_at IS NULL;
